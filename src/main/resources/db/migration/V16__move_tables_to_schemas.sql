-- Logical schemas for privilege boundaries. Existing data is moved, not copied.

CREATE SCHEMA IF NOT EXISTS identity;
CREATE SCHEMA IF NOT EXISTS catalog;
CREATE SCHEMA IF NOT EXISTS purchasing;
CREATE SCHEMA IF NOT EXISTS sales;
CREATE SCHEMA IF NOT EXISTS ops;
CREATE SCHEMA IF NOT EXISTS reporting;

ALTER TABLE organizations SET SCHEMA identity;
ALTER TABLE users SET SCHEMA identity;
ALTER TABLE refresh_tokens SET SCHEMA identity;
ALTER TABLE otp_codes SET SCHEMA identity;
ALTER TABLE employees SET SCHEMA identity;

ALTER TABLE products SET SCHEMA catalog;
ALTER TABLE inventory_movements SET SCHEMA catalog;

ALTER TABLE suppliers SET SCHEMA purchasing;
ALTER TABLE purchase_orders SET SCHEMA purchasing;
ALTER TABLE purchase_order_items SET SCHEMA purchasing;

ALTER TABLE customers SET SCHEMA sales;
ALTER TABLE sales_orders SET SCHEMA sales;
ALTER TABLE sales_order_items SET SCHEMA sales;

ALTER TABLE api_keys SET SCHEMA ops;
ALTER TABLE audit_events SET SCHEMA ops;

GRANT USAGE ON SCHEMA identity, catalog, purchasing, sales, ops, reporting TO PUBLIC;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA identity TO PUBLIC;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA catalog TO PUBLIC;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA purchasing TO PUBLIC;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA sales TO PUBLIC;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA ops TO PUBLIC;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA reporting TO PUBLIC;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA identity TO PUBLIC;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA catalog TO PUBLIC;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA purchasing TO PUBLIC;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA sales TO PUBLIC;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA ops TO PUBLIC;
